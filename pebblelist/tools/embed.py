#!/usr/bin/env python3
"""Regenerates src/pkjs/page.js from config.html (run this after editing config.html).

  python3 tools/embed.py

The page is shrunk a little (indentation, blank lines, full-line comments, the home-screen
icon tags) and written as a JavaScript string that src/pkjs/index.js opens offline.
"""
import json, os, re, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(root, 'config.html'), encoding='utf-8').read()

html = src
html = re.sub(r'<link rel="(?:apple-touch-icon|icon)"[^>]*>\s*', '', html)      # big, unused offline
html = re.sub(r'<!--[\s\S]*?-->', '', html)
html = re.sub(r'/\*(?!__PL_INIT__)[\s\S]*?\*/', '', html)                          # /* comments */
out = []
for line in html.split('\n'):
    t = line.strip()
    if not t or t.startswith('//'):
        continue
    out.append(t)
html = '\n'.join(out)

js = '// GENERATED by tools/embed.py from config.html - do not edit by hand.\nmodule.exports = ' + \
     json.dumps(html, ensure_ascii=True) + ';\n'
dst = os.path.join(root, 'src', 'pkjs', 'page.js')
open(dst, 'w', encoding='utf-8').write(js)
print('config.html %d bytes -> page.js %d bytes' % (len(src.encode()), len(js.encode())))
